using System.Text.Json.Nodes;
using Npgsql;
using WeatherRisk.Platform;

var builder = WebApplication.CreateBuilder(args);
builder.AddPlatform();
builder.Services.AddSingleton(new Database(() => new NpgsqlConnection(Hosting.Required(builder.Configuration, "DATABASE_URL"))));
builder.Services.AddHealthChecks().AddCheck<Database>("database");
var app = builder.Build();
app.UsePlatform("community");
var db = app.Services.GetRequiredService<Database>();
await db.Execute("""
CREATE TABLE IF NOT EXISTS communities(
id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
nombre varchar(200) NOT NULL UNIQUE, municipio varchar(100) NOT NULL,
departamento varchar(100) NOT NULL, pais varchar(100) NOT NULL,
latitud numeric(10,7), longitud numeric(10,7), descripcion text, activo boolean NOT NULL DEFAULT true);
""");
var api = app.MapGroup("/api/comunidades").RequireAuthorization();
var internalApi = app.MapGroup("/internal/communities");

async Task<JsonArray> List(HttpRequest request, Peers peers)
{
    var sql = "SELECT * FROM communities WHERE true";
    var parameters = new Dictionary<string, object?>();
    foreach (var field in new[] { "municipio", "departamento" })
        if (request.Query.TryGetValue(field, out var filter)) { sql += $" AND {field} ILIKE @{field}"; parameters[field] = "%" + filter + "%"; }
    if (request.Query.TryGetValue("buscar", out var search)) { sql += " AND (nombre ILIKE @buscar OR municipio ILIKE @buscar)"; parameters["buscar"] = "%" + search + "%"; }
    if (bool.TryParse(request.Query["activo"], out var active)) { sql += " AND activo=@activo"; parameters["activo"] = active; }
    var pagination = "";
    if (request.Query.ContainsKey("page"))
    {
        if (!int.TryParse(request.Query["page"], out var page) || page < 1) throw new ApiError(400, "Invalid page");
        var size = int.TryParse(request.Query["pageSize"], out var n) ? n : 200;
        if (size < 1 || size > 200) throw new ApiError(400, "Invalid pageSize");
        pagination = $" LIMIT {size} OFFSET {(long)(page-1)*size}";
    }
    var rows = await db.Query(sql + " ORDER BY id" + pagination, parameters);
    var counts = await peers.Get("SENSOR_URL", "/internal/sensors/counts") as JsonArray ?? [];
    foreach (var row in rows)
    {
        var count = counts.FirstOrDefault(c => c!["comunidadId"]!.GetValue<int>() == row!["id"]!.GetValue<int>());
        row!["sensoresActivos"] = count?["activos"]?.DeepClone() ?? JsonValue.Create(0);
        row["sensoresTotales"] = count?["total"]?.DeepClone() ?? JsonValue.Create(0);
    }
    return rows;
}
api.MapGet("", List);
internalApi.MapGet("", List);
internalApi.MapGet("/lookup", async () => await db.Query("SELECT id,nombre FROM communities ORDER BY id"));
async Task<IResult> Find(int id)
{
    var rows = await db.Query("SELECT * FROM communities WHERE id=@id", new() { ["id"] = id });
    return rows.Count == 0 ? Results.NotFound() : Results.Json(rows[0]!.DeepClone());
}
api.MapGet("/{id:int}", Find);
internalApi.MapGet("/{id:int}", Find);

Dictionary<string, object?> Values(JsonObject body) => new()
{
    ["nombre"] = Hosting.Text(body, "nombre"), ["municipio"] = Hosting.Text(body, "municipio", 100),
    ["departamento"] = Hosting.Text(body, "departamento", 100), ["pais"] = Hosting.Text(body, "pais", 100),
    ["latitud"] = body["latitud"]?.GetValue<decimal>(), ["longitud"] = body["longitud"]?.GetValue<decimal>(),
    ["descripcion"] = body["descripcion"]?.GetValue<string>(), ["activo"] = body["activo"]?.GetValue<bool>() ?? true
};
api.MapPost("", async (JsonObject body, HttpContext context, Peers peers) =>
{
    try
    {
        var rows = await db.Query("INSERT INTO communities(nombre,municipio,departamento,pais,latitud,longitud,descripcion,activo) VALUES(@nombre,@municipio,@departamento,@pais,@latitud,@longitud,@descripcion,@activo) RETURNING *", Values(body));
        await peers.Audit(Hosting.Actor(context), "CREAR_COMUNIDAD", "community", rows[0]!["id"]!.GetValue<int>());
        return Results.Created("/api/comunidades/" + rows[0]!["id"], rows[0]!.DeepClone());
    }
    catch (PostgresException e) when (e.SqlState == "23505") { throw new ApiError(409, "Community already exists."); }
}).RequireAuthorization(p => p.RequireRole("ADMIN"));
api.MapPut("/{id:int}", async (int id, JsonObject body, HttpContext context, Peers peers) =>
{
    var values = Values(body); values["id"] = id;
    var rows = await db.Query("UPDATE communities SET nombre=@nombre,municipio=@municipio,departamento=@departamento,pais=@pais,latitud=@latitud,longitud=@longitud,descripcion=@descripcion,activo=@activo WHERE id=@id RETURNING *", values);
    if (rows.Count == 0) return Results.NotFound();
    await peers.Audit(Hosting.Actor(context), "EDITAR_COMUNIDAD", "community", id);
    return Results.Json(rows[0]!.DeepClone());
}).RequireAuthorization(p => p.RequireRole("ADMIN"));
api.MapPatch("/{id:int}/estado", async (int id, JsonObject body, HttpContext context, Peers peers) =>
{
    var changed = await db.Execute("UPDATE communities SET activo=@activo WHERE id=@id", new() { ["id"] = id, ["activo"] = body["activo"]?.GetValue<bool>() ?? throw new ApiError(400, "activo required") });
    if (changed == 0) return Results.NotFound();
    await peers.Audit(Hosting.Actor(context), "ESTADO_COMUNIDAD", "community", id);
    return Results.NoContent();
}).RequireAuthorization(p => p.RequireRole("ADMIN"));
app.Run();
